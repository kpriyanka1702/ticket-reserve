package com.ticketreserve;

import org.jdbi.v3.core.Handle;
import org.jdbi.v3.core.Jdbi;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.sql.Timestamp;
import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import java.util.regex.Pattern;

/**
 * MySQL is the inventory. A hold is one conditional update
 * ({@code available = available - qty WHERE available >= qty}) plus a Redis
 * key that expires. Confirm keeps the decrement. Cancel and the sweeper put
 * the tickets back.
 */
public final class ReservationService {

    private static final Logger log = LoggerFactory.getLogger(ReservationService.class);
    private static final int MAX_QTY = 8;
    private static final Pattern EMAIL = Pattern.compile("^[^\\s@]{1,64}@[^\\s@]{1,190}$");
    private static final Pattern ID = Pattern.compile(
            "^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$");

    private static final String[] DDL = {
            """
            CREATE TABLE IF NOT EXISTS events (
              id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
              name VARCHAR(200) NOT NULL,
              venue VARCHAR(200) NOT NULL,
              starts_at TIMESTAMP NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS inventory (
              event_id BIGINT PRIMARY KEY,
              capacity INT NOT NULL,
              available INT NOT NULL,
              price_cents INT NOT NULL
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS reservations (
              id VARCHAR(36) PRIMARY KEY,
              event_id BIGINT NOT NULL,
              qty INT NOT NULL,
              status VARCHAR(16) NOT NULL,
              holder_email VARCHAR(254) NOT NULL,
              created_at TIMESTAMP NOT NULL,
              expires_at TIMESTAMP NOT NULL
            )
            """
    };

    private final Jdbi jdbi;
    private final HoldStore holds;
    private final int holdTtlSeconds;

    public ReservationService(Jdbi jdbi, HoldStore holds, int holdTtlSeconds) {
        this.jdbi = jdbi;
        this.holds = holds;
        this.holdTtlSeconds = holdTtlSeconds;
    }

    public void migrate() {
        jdbi.useHandle(handle -> {
            for (String statement : DDL) {
                handle.execute(statement);
            }
        });
    }

    public void seedIfEmpty() {
        Integer count = jdbi.withHandle(handle ->
                handle.createQuery("SELECT COUNT(*) FROM events").mapTo(Integer.class).one());
        if (count != null && count > 0) {
            return;
        }
        insertEvent(1, "City Derby", "Harbor Stadium", Instant.parse("2026-12-01T19:30:00Z"), 200, 7500);
        insertEvent(2, "Late Show", "North Hall", Instant.parse("2026-12-05T21:00:00Z"), 40, 3200);
    }

    public void insertEvent(long id, String name, String venue, Instant startsAt, int capacity, int priceCents) {
        if (capacity < 1 || priceCents < 0) {
            throw new IllegalArgumentException("capacity and price must be non-negative");
        }
        jdbi.useTransaction(handle -> {
            handle.createUpdate("""
                    INSERT INTO events (id, name, venue, starts_at)
                    VALUES (:id, :name, :venue, :starts)
                    """)
                    .bind("id", id)
                    .bind("name", name)
                    .bind("venue", venue)
                    .bind("starts", Timestamp.from(startsAt))
                    .execute();
            handle.createUpdate("""
                    INSERT INTO inventory (event_id, capacity, available, price_cents)
                    VALUES (:id, :capacity, :capacity, :price)
                    """)
                    .bind("id", id)
                    .bind("capacity", capacity)
                    .bind("price", priceCents)
                    .execute();
        });
    }

    public List<EventView> listEvents() {
        return jdbi.withHandle(handle -> handle.createQuery("""
                SELECT e.id, e.name, e.venue, e.starts_at, i.capacity, i.available, i.price_cents
                  FROM events e
                  JOIN inventory i ON i.event_id = e.id
                 ORDER BY e.starts_at
                """).map((rs, ctx) -> new EventView(
                rs.getLong("id"),
                rs.getString("name"),
                rs.getString("venue"),
                rs.getTimestamp("starts_at").toInstant(),
                rs.getInt("capacity"),
                rs.getInt("available"),
                rs.getInt("price_cents")
        )).list());
    }

    public EventView getEvent(long eventId) {
        return jdbi.withHandle(handle -> {
            Optional<EventView> row = handle.createQuery("""
                    SELECT e.id, e.name, e.venue, e.starts_at, i.capacity, i.price_cents
                      FROM events e
                      JOIN inventory i ON i.event_id = e.id
                     WHERE e.id = :id
                    """)
                    .bind("id", eventId)
                    .map((rs, ctx) -> new EventView(
                            rs.getLong("id"),
                            rs.getString("name"),
                            rs.getString("venue"),
                            rs.getTimestamp("starts_at").toInstant(),
                            rs.getInt("capacity"),
                            0,
                            rs.getInt("price_cents")))
                    .findOne();
            EventView event = row.orElseThrow(() -> new ApiException(404, "not_found", "Event not found"));
            int available = holds.cachedAvailable(eventId).orElseGet(() -> {
                int value = queryAvailable(handle, eventId);
                holds.cacheAvailable(eventId, value);
                return value;
            });
            return new EventView(event.id(), event.name(), event.venue(), event.startsAt(),
                    event.capacity(), available, event.priceCents());
        });
    }

    public HoldView hold(long eventId, int qty, String email) {
        if (qty < 1 || qty > MAX_QTY) {
            throw new ApiException(400, "bad_request", "Quantity must be from 1 to " + MAX_QTY);
        }
        String holder = email == null ? "" : email.trim();
        if (!EMAIL.matcher(holder).matches()) {
            throw new ApiException(400, "bad_request", "A valid email is required");
        }
        String id = UUID.randomUUID().toString();
        Instant now = Instant.now();
        Instant expires = now.plusSeconds(holdTtlSeconds);

        jdbi.useTransaction(handle -> {
            Integer event = handle.createQuery("SELECT 1 FROM events WHERE id = :id")
                    .bind("id", eventId)
                    .mapTo(Integer.class)
                    .findOne()
                    .orElse(null);
            if (event == null) {
                throw new ApiException(404, "not_found", "Event not found");
            }
            // One row lock. The second buyer updates 0 rows and does not get the ticket.
            int updated = handle.createUpdate("""
                    UPDATE inventory
                       SET available = available - :qty
                     WHERE event_id = :eventId
                       AND available >= :qty
                    """)
                    .bind("qty", qty)
                    .bind("eventId", eventId)
                    .execute();
            if (updated != 1) {
                throw new ApiException(409, "sold_out", "Not enough tickets left");
            }
            handle.createUpdate("""
                    INSERT INTO reservations
                      (id, event_id, qty, status, holder_email, created_at, expires_at)
                    VALUES
                      (:id, :eventId, :qty, 'HELD', :email, :created, :expires)
                    """)
                    .bind("id", id)
                    .bind("eventId", eventId)
                    .bind("qty", qty)
                    .bind("email", holder)
                    .bind("created", Timestamp.from(now))
                    .bind("expires", Timestamp.from(expires))
                    .execute();
        });

        try {
            holds.save(id, holdTtlSeconds);
        } catch (RuntimeException e) {
            log.warn("hold key was not stored; returning tickets for {}", id);
            release(id, "RELEASED");
            throw new ApiException(503, "hold_store_unavailable", "Could not place a hold. Try again.");
        }
        holds.invalidate(eventId);
        return new HoldView(id, eventId, qty, expires, available(eventId));
    }

    public ConfirmView confirm(String id) {
        requireId(id);
        if (!holds.exists(id)) {
            release(id, "EXPIRED");
            throw new ApiException(409, "hold_expired", "Hold expired");
        }
        long[] row = jdbi.inTransaction(handle -> {
            int marked = handle.createUpdate("""
                    UPDATE reservations
                       SET status = 'CONFIRMED'
                     WHERE id = :id
                       AND status = 'HELD'
                       AND expires_at > :now
                    """)
                    .bind("id", id)
                    .bind("now", Timestamp.from(Instant.now()))
                    .execute();
            if (marked != 1) {
                throw new ApiException(409, "hold_expired", "Hold expired");
            }
            return handle.createQuery("SELECT event_id, qty FROM reservations WHERE id = :id")
                    .bind("id", id)
                    .map((rs, ctx) -> new long[]{rs.getLong("event_id"), rs.getInt("qty")})
                    .one();
        });
        bestEffort(() -> holds.delete(id));
        bestEffort(() -> holds.invalidate(row[0]));
        return new ConfirmView(id, row[0], (int) row[1], "CONFIRMED");
    }

    public boolean release(String id) {
        requireId(id);
        return release(id, "RELEASED");
    }

    public int expireDue() {
        List<String> ids = jdbi.withHandle(handle -> handle.createQuery("""
                SELECT id FROM reservations
                 WHERE status = 'HELD' AND expires_at <= :now
                """)
                .bind("now", Timestamp.from(Instant.now()))
                .mapTo(String.class)
                .list());
        int released = 0;
        for (String id : ids) {
            if (release(id, "EXPIRED")) {
                released++;
            }
        }
        return released;
    }

    public int available(long eventId) {
        return jdbi.withHandle(handle -> queryAvailable(handle, eventId));
    }

    public String status(String id) {
        return jdbi.withHandle(handle -> handle.createQuery("SELECT status FROM reservations WHERE id = :id")
                .bind("id", id)
                .mapTo(String.class)
                .findOne()
                .orElse(null));
    }

    private boolean release(String id, String status) {
        long[] restored = jdbi.inTransaction(handle -> {
            int marked = handle.createUpdate("""
                    UPDATE reservations
                       SET status = :status
                     WHERE id = :id AND status = 'HELD'
                    """)
                    .bind("status", status)
                    .bind("id", id)
                    .execute();
            if (marked != 1) {
                return null;
            }
            long eventId = handle.createQuery("SELECT event_id FROM reservations WHERE id = :id")
                    .bind("id", id)
                    .mapTo(Long.class)
                    .one();
            int qty = handle.createQuery("SELECT qty FROM reservations WHERE id = :id")
                    .bind("id", id)
                    .mapTo(Integer.class)
                    .one();
            int updated = handle.createUpdate("""
                    UPDATE inventory
                       SET available = available + :qty
                     WHERE event_id = :eventId
                       AND available + :qty <= capacity
                    """)
                    .bind("qty", qty)
                    .bind("eventId", eventId)
                    .execute();
            if (updated != 1) {
                throw new IllegalStateException("inventory restore failed for event " + eventId);
            }
            return new long[]{eventId};
        });
        if (restored == null) {
            return false;
        }
        bestEffort(() -> holds.delete(id));
        bestEffort(() -> holds.invalidate(restored[0]));
        return true;
    }

    private static int queryAvailable(Handle handle, long eventId) {
        return handle.createQuery("SELECT available FROM inventory WHERE event_id = :id")
                .bind("id", eventId)
                .mapTo(Integer.class)
                .findOne()
                .orElseThrow(() -> new ApiException(404, "not_found", "Event not found"));
    }

    private static void requireId(String id) {
        if (id == null || !ID.matcher(id).matches()) {
            throw new ApiException(400, "bad_request", "Invalid hold id");
        }
    }

    private static void bestEffort(Runnable action) {
        try {
            action.run();
        } catch (RuntimeException e) {
            log.warn("redis follow-up failed: {}", e.getClass().getSimpleName());
        }
    }

    public record EventView(long id, String name, String venue, Instant startsAt,
                            int capacity, int available, int priceCents) {
    }

    public record HoldView(String id, long eventId, int qty, Instant expiresAt, int available) {
    }

    public record ConfirmView(String id, long eventId, int qty, String status) {
    }
}
